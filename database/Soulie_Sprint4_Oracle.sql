-- Soulie Sprint 4 - Oracle
-- Estrutura alinhada às tabelas e colunas usadas pelos DAOs atuais.
-- Execute em um schema Oracle vazio (Oracle 12c ou superior para IDENTITY).
-- Os IDs das entidades são gerados pelo banco com GENERATED ALWAYS.

CREATE TABLE USUARIO (
    ID_USUARIO NUMBER GENERATED ALWAYS AS IDENTITY,
    NM_USUARIO VARCHAR2(50 CHAR) NOT NULL,
    DS_EMAIL VARCHAR2(100 CHAR) NOT NULL,
    QT_PONTOS_ACUMULADOS NUMBER(10) DEFAULT 0 NOT NULL,
    ST_USUARIO VARCHAR2(1 CHAR) DEFAULT 'A' NOT NULL,
    DS_IDENTIFICADOR_JORNADA VARCHAR2(100 CHAR),
    CONSTRAINT USUARIO_PK PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT CK_USUARIO_STATUS CHECK (ST_USUARIO IN ('A', 'I'))
);

CREATE TABLE MISSAO (
    ID_MISSAO NUMBER GENERATED ALWAYS AS IDENTITY,
    NM_MISSAO VARCHAR2(60 CHAR) NOT NULL,
    DS_MISSAO VARCHAR2(200 CHAR) NOT NULL,
    QT_PONTOS_RECOMPENSA NUMBER(10) NOT NULL,
    ID_USUARIO_CRIADOR NUMBER,
    QT_META_DIAS NUMBER(10) NOT NULL,
    CONSTRAINT MISSAO_PK PRIMARY KEY (ID_MISSAO),
    CONSTRAINT MISSAO_USUARIO_CRIADOR_FK FOREIGN KEY (ID_USUARIO_CRIADOR)
        REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE CONQUISTA (
    ID_CONQUISTA NUMBER GENERATED ALWAYS AS IDENTITY,
    NM_CONQUISTA VARCHAR2(70 CHAR) NOT NULL,
    DS_CONQUISTA VARCHAR2(80 CHAR),
    CONSTRAINT CONQUISTA_PK PRIMARY KEY (ID_CONQUISTA)
);

CREATE TABLE COMUNIDADE (
    ID_COMUNIDADE NUMBER GENERATED ALWAYS AS IDENTITY,
    NM_COMUNIDADE VARCHAR2(50 CHAR) NOT NULL,
    DS_TEMA VARCHAR2(90 CHAR),
    CONSTRAINT COMUNIDADE_PK PRIMARY KEY (ID_COMUNIDADE)
);

CREATE TABLE AVATAR (
    ID_AVATAR NUMBER GENERATED ALWAYS AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    NR_NIVEL_EVOLUCAO NUMBER(10) DEFAULT 1 NOT NULL,
    QT_EXPERIENCIA NUMBER(10) DEFAULT 0 NOT NULL,
    DS_TEMPERAMENTO VARCHAR2(70 CHAR),
    CONSTRAINT AVATAR_PK PRIMARY KEY (ID_AVATAR),
    CONSTRAINT AVATAR_USUARIO_FK FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT AVATAR_USUARIO_UK UNIQUE (ID_USUARIO)
);

CREATE TABLE STREAK (
    ID_STREAK NUMBER GENERATED ALWAYS AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    QT_DIAS_CONSECUTIVOS NUMBER(10) NOT NULL,
    DT_ULTIMO_ACESSO DATE NOT NULL,
    CONSTRAINT STREAK_PK PRIMARY KEY (ID_STREAK),
    CONSTRAINT STREAK_USUARIO_FK FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE ATIVIDADE (
    ID_REGISTRO NUMBER GENERATED ALWAYS AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    ID_MISSAO NUMBER NOT NULL,
    DT_REGISTRO DATE NOT NULL,
    DS_OBSERVACAO VARCHAR2(200 CHAR),
    CONSTRAINT ATIVIDADE_PK PRIMARY KEY (ID_REGISTRO),
    CONSTRAINT ATIVIDADE_USUARIO_FK FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT ATIVIDADE_MISSAO_FK FOREIGN KEY (ID_MISSAO)
        REFERENCES MISSAO (ID_MISSAO)
);

CREATE TABLE USUARIO_MISSAO (
    ID_USUARIO NUMBER NOT NULL,
    ID_MISSAO NUMBER NOT NULL,
    DT_INICIO DATE NOT NULL,
    DT_CONCLUSAO DATE,
    ST_MISSAO VARCHAR2(15 CHAR) NOT NULL,
    CONSTRAINT USUARIO_MISSAO_PK PRIMARY KEY (ID_USUARIO, ID_MISSAO),
    CONSTRAINT USUARIO_MISSAO_USUARIO_FK FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT USUARIO_MISSAO_MISSAO_FK FOREIGN KEY (ID_MISSAO)
        REFERENCES MISSAO (ID_MISSAO)
);

CREATE TABLE USUARIO_CONQUISTA (
    ID_USUARIO NUMBER NOT NULL,
    ID_CONQUISTA NUMBER NOT NULL,
    DT_CONQUISTA DATE NOT NULL,
    CONSTRAINT USUARIO_CONQUISTA_PK PRIMARY KEY (ID_USUARIO, ID_CONQUISTA),
    CONSTRAINT USUARIO_CONQUISTA_USUARIO_FK FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT USUARIO_CONQUISTA_CONQUISTA_FK FOREIGN KEY (ID_CONQUISTA)
        REFERENCES CONQUISTA (ID_CONQUISTA)
);

CREATE TABLE USUARIO_COMUNIDADE (
    ID_USUARIO NUMBER NOT NULL,
    ID_COMUNIDADE NUMBER NOT NULL,
    DT_INGRESSO_GRUPO DATE NOT NULL,
    CONSTRAINT USUARIO_COMUNIDADE_PK PRIMARY KEY (ID_USUARIO, ID_COMUNIDADE),
    CONSTRAINT USUARIO_COMUNIDADE_USUARIO_FK FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT USUARIO_COMUNIDADE_COMUNIDADE_FK FOREIGN KEY (ID_COMUNIDADE)
        REFERENCES COMUNIDADE (ID_COMUNIDADE)
);

CREATE TABLE POSTAGEM (
    ID_POSTAGEM NUMBER GENERATED ALWAYS AS IDENTITY,
    DS_CONTEUDO_POSTAGEM VARCHAR2(200 CHAR) NOT NULL,
    NM_POSTAGEM VARCHAR2(80 CHAR) NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    ID_COMUNIDADE NUMBER NOT NULL,
    DT_POSTAGEM DATE NOT NULL,
    CONSTRAINT POSTAGEM_PK PRIMARY KEY (ID_POSTAGEM),
    CONSTRAINT POSTAGEM_USUARIO_FK FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT POSTAGEM_COMUNIDADE_FK FOREIGN KEY (ID_COMUNIDADE)
        REFERENCES COMUNIDADE (ID_COMUNIDADE)
);

