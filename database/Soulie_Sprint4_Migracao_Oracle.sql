-- Migracao da estrutura Sprint 3 para os campos usados pelo codigo Sprint 4.
-- Execute uma unica vez sobre um schema que ja tenha as tabelas USUARIO,
-- AVATAR e MISSAO da Sprint 3, mas ainda nao tenha ATIVIDADE.
-- Nao execute depois do script Soulie_Sprint4_Oracle.sql completo.

ALTER TABLE USUARIO
    ADD (DS_IDENTIFICADOR_JORNADA VARCHAR2(100 CHAR));

ALTER TABLE AVATAR
    ADD (QT_EXPERIENCIA NUMBER(10) DEFAULT 0 NOT NULL);

ALTER TABLE MISSAO
    ADD (ID_USUARIO_CRIADOR NUMBER, QT_META_DIAS NUMBER(10) DEFAULT 1 NOT NULL);

ALTER TABLE MISSAO
    ADD CONSTRAINT MISSAO_USUARIO_CRIADOR_FK
    FOREIGN KEY (ID_USUARIO_CRIADOR)
    REFERENCES USUARIO (ID_USUARIO);

CREATE TABLE ATIVIDADE (
    ID_REGISTRO NUMBER GENERATED ALWAYS AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    ID_MISSAO NUMBER NOT NULL,
    DT_REGISTRO DATE NOT NULL,
    DS_OBSERVACAO VARCHAR2(200 CHAR),
    CONSTRAINT ATIVIDADE_PK PRIMARY KEY (ID_REGISTRO),
    CONSTRAINT ATIVIDADE_USUARIO_FK FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT ATIVIDADE_MISSAO_FK FOREIGN KEY (ID_MISSAO)
        REFERENCES MISSAO (ID_MISSAO)
);
